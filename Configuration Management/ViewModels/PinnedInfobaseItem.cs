using Configuration_Management.Models;

namespace Configuration_Management.ViewModels;

/// <summary>
/// Обёртка закреплённой базы для элемента дерева в узле «Закреплённые» (Windows/WPF,
/// аналог <c>PinnedInfobaseItem.Avalonia.cs</c>, issue #301; на Windows дубль данных
/// устранён в 0.3.9.115, issue #314). Раньше один и тот же экземпляр
/// <see cref="Infobase"/> попадал в дерево дважды — в узел «Закреплённые» (первый
/// корень) и в собственную группу базы, из-за чего выделение строки (TreeView
/// синхронизирует выбор по данным, а повторное восстановление выбора ищет контейнер
/// по данным) подсвечивало копию в «Закреплённых», а клик по одной закреплённой базе
/// подсвечивал весь узел «Закреплённые». Уникальный объект данных у каждой строки
/// дерева делает такое перекрашивание структурно невозможным: поиск контейнера по
/// данным всегда находит единственный контейнер.
///
/// Обёртка живёт только элементом дерева (Items узла «Закреплённые»); сама строка
/// строится по тому же DataTemplate, что и обычная база, но через ContentControl
/// с <see cref="Base"/> (см. MainWindow.xaml), поэтому все привязки строки, кнопки
/// и команды получают реальную базу и работают как раньше. Точки разворачивания:
/// обработчики кликов, OnMainTree_SelectedItemChanged, VisibleInfobasesInOrder,
/// поиск контейнера по данным, DnD и команды строки (UnwrapInfobase).
/// </summary>
public sealed class PinnedInfobaseItem
{
    public PinnedInfobaseItem(Infobase infobase) => Base = infobase;

    /// <summary>Реальная информационная база этой строки.</summary>
    public Infobase Base { get; }
}