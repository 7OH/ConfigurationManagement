namespace Configuration_Management.Models;

/// <summary>
/// Глубина проверки резервной копии (функция 8): быстрая проверка структуры либо
/// полное тестовое восстановление. Выбирается пользователем при ручной проверке
/// и задаётся в задании по расписанию «Проверка резервных копий».
/// </summary>
public enum BackupValidationDepth
{
    /// <summary>
    /// Быстро: структура/целостность заголовка. Для .cf — успешный CREATEINFOBASE
    /// из шаблона; для .zip/.rar — чтение каталога архива; для .dt — чтение файла
    /// и проверка сигнатуры выгрузки.
    /// </summary>
    Fast,

    /// <summary>
    /// Полно: тестовое восстановление. Для .dt — restore ibcmd/1cv8 во временную
    /// файловую базу; для .cf — CREATEINFOBASE + DumpConfigToFiles; для .zip/.rar —
    /// полная проверка CRC/чтение всех записей (rar t).
    /// </summary>
    Full
}