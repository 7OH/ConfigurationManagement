namespace Configuration_Management.Services;

/// <summary>
/// Системные уведомления ОС о завершении фоновых операций (функция №4): резервная копия,
/// задание по расписанию, найденное обновление приложения. Вызывается из фоновых потоков
/// (планировщик заданий, автообновление), когда приложение может быть свёрнуто в трей —
/// именно там уведомление и показывается.
/// Реализации обязаны тихо деградировать: при недоступности трея (Windows) или отсутствии
/// notify-send (Linux) вызов — no-op, исключения наружу не всплывают.
/// </summary>
public interface INotificationService
{
    /// <summary>
    /// Показывает системное уведомление (заголовок + текст). Fire-and-forget: метод не
    /// блокирует вызывающий поток, любые ошибки платформы гасятся внутри реализации.
    /// </summary>
    void Show(string title, string message);
}