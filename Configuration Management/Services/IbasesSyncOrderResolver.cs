namespace Configuration_Management.Services;

/// <summary>
/// Определяет порядок операций двусторонней синхронизации с файлом ibases.v8i (issue #278).
/// В режиме «в обе стороны» синхронизация всегда шла «сначала выгрузка, потом загрузка»:
/// после ручного восстановления пользователем файла ibases.v8i первый шаг — экспорт —
/// сопоставлял запись по ID 1С и переименовывал её обратно в имя из приложения, записывая
/// его в файл, а импорт читал уже перезаписанный файл. Решение о порядке вынесено в этот
/// хелпер, чтобы его можно было покрыть юнит-тестами.
/// </summary>
public static class IbasesSyncOrderResolver
{
    /// <summary>
    /// Возвращает true, если при синхронизации «в обе стороны» сначала должна выполняться
    /// загрузка из файла, а только потом выгрузка приложения:
    /// <list type="bullet">
    /// <item>метка последней выгрузки приложения не задана (<paramref name="lastAppExportUtc"/>
    /// равен default(DateTime), т.е. первый запуск) — безопасно не перезаписывать файл,
    /// который приложение ещё ни разу не писало;</item>
    /// <item>файл менялся позже последней выгрузки приложения (внешнее изменение — ручное
    /// восстановление/подмена файла) — приоритет у содержимого файла.</item>
    /// </list>
    /// Во всех остальных случаях возвращается false: прежний порядок — выгрузка, затем загрузка.
    /// </summary>
    /// <param name="fileLastWriteUtc">Момент последнего изменения файла ibases.v8i (UTC).</param>
    /// <param name="lastAppExportUtc">Момент последней успешной выгрузки приложения (UTC).</param>
    public static bool ShouldImportFirst(DateTime fileLastWriteUtc, DateTime lastAppExportUtc)
        => lastAppExportUtc == default || fileLastWriteUtc > lastAppExportUtc;
}